"""Generates src/bio/blosum62.ts from Biopython's copy of the NCBI BLOSUM62 matrix (verified cell-for-cell
identical to https://ftp.ncbi.nlm.nih.gov/blast/matrices/BLOSUM62 in Phase 1: 576 cells, 0 differences)."""
from Bio.Align import substitution_matrices

m = substitution_matrices.load("BLOSUM62")
letters = "ARNDCQEGHILKMFPSTWYVBZX*"
assert list(m.alphabet) == list(letters), m.alphabet
rows = []
for a in letters:
    rows.append("  [" + ", ".join(str(int(m[a][b])) for b in letters) + "],")
out = f"""// GENERATED by tools/gen_blosum.py - do not edit. BLOSUM62 (Henikoff & Henikoff 1992), NCBI distribution.
// Row/column order: {letters}

/** Residue letters in matrix order. */
export const BLOSUM62_LETTERS = '{letters}';

/** BLOSUM62 integer scores, indexed [row][col] in BLOSUM62_LETTERS order. */
export const BLOSUM62: readonly (readonly number[])[] = [
""" + "\n".join(rows) + "\n];\n"
open("src/bio/blosum62.ts", "w").write(out)
print("wrote src/bio/blosum62.ts")
